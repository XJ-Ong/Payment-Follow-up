"""SQLAlchemy 2.0 models for the plugin-owned tables.

(Company, AppUser, Client, Project, Milestone, ApprovedLeave, PublicHoliday)
arrive through MockOrbyteAdapter, so references to them are
plain uuid columns with no foreign key ("Orbyte ref").
"""

from datetime import date, datetime
from decimal import Decimal
from uuid import UUID

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column

from .base import Base


def _uuid_pk() -> Mapped[UUID]:
    """Primary key column: uuid generated by Postgres when no id is supplied."""
    return mapped_column(
        PG_UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


def _company_id() -> Mapped[UUID]:
    """Orbyte ref: tenant column indexed on every table (schema.md section 6)."""
    return mapped_column(PG_UUID(as_uuid=True), index=True)


