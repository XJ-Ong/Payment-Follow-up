        UniqueConstraint("company_id", "invoice_no", name="uq_invoice_company_invoice_no"),
        CheckConstraint("due_date >= issue_date", name="ck_invoice_due_date"),
        CheckConstraint("total_amount > 0", name="ck_invoice_total_amount"),
        CheckConstraint("status IN ('open', 'partially_paid', 'paid', 'void')", name="ck_invoice_status"),
        CheckConstraint("source IN ('manual', 'csv', 'milestone')", name="ck_invoice_source"),
        Index("ix_invoice_company_status_due", "company_id", "status", "due_date"),
        Index("ix_invoice_company_client", "company_id", "client_id"),
        # One invoice per milestone: partial unique index (nulls do not collide).
